"""Generate immutable codec plans from public n,q, independently of C init."""
from __future__ import annotations
import argparse
from pathlib import Path

MAX_N = 4096
MAX_Q = 32767

def plan(n: int, q: int) -> dict:
    if not 1 <= n <= MAX_N or not 3 <= q <= MAX_Q or not q & 1:
        raise ValueError('require 1<=n<=4096 and odd 3<=q<=32767')
    divisor=1; digits=0
    while divisor*q < 1 << 63:
        divisor*=q; digits+=1
    chunks=(n+digits-1)//digits
    shift=64-divisor.bit_length()
    normalized=divisor << shift
    encoded_bytes=((q**n-1).bit_length()+7)//8
    processed=n-(chunks-1)*digits
    packing=[]
    for chunk in range(chunks):
        if chunk: processed+=digits
        packing.append(((q**processed-1).bit_length()+63)//64)
    remaining=(1 << (8*encoded_bytes))-1
    unpacking=[]
    for _ in range(chunks):
        unpacking.append((remaining.bit_length()+63)//64)
        remaining//=divisor
    return dict(n=n,q=q,encoded_bytes=encoded_bytes,limbs=(encoded_bytes+7)//8,
                digits=digits,chunks=chunks,shift=shift,divisor=divisor,
                normalized_divisor=normalized,
                reciprocal=(1 << 128)//normalized-(1 << 64),
                digit_reciprocal=((1 << 64)+q-1)//q,
                pack_limbs=packing,unpack_limbs=unpacking)

def emit(p: dict, name: str) -> str:
    lines=[f'static const ct_radix_plan {name} = {{']
    for field, value in p.items():
        if isinstance(value,list):
            lines.append(f'    .{field}={{')
            for start in range(0,len(value),16):
                lines.append('        '+','.join(map(str,value[start:start+16]))+',')
            lines.append('    },')
        elif field in ('divisor','normalized_divisor','reciprocal','digit_reciprocal'):
            lines.append(f'    .{field}=UINT64_C({value}),')
        else: lines.append(f'    .{field}={value},')
    lines.append('};')
    return '\n'.join(lines)+'\n'

def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--n',type=int)
    parser.add_argument('--q',type=int)
    parser.add_argument('--symbol')
    parser.add_argument('--out',type=Path,default=Path(__file__).with_name('ct_radix_generated.h'))
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    if (args.n is None) != (args.q is None): parser.error('--n and --q are a pair')
    pairs=[(512,211),(1024,307),(1024,331),(1024,373)] if args.n is None else [(args.n,args.q)]
    if args.symbol and len(pairs) != 1: parser.error('--symbol requires --n and --q')
    text='/* Generated by ct_radix_generate.py; public parameters only. */\n'
    text+='#ifndef CNTRU_COMMON_CT_RADIX_GENERATED_H\n#define CNTRU_COMMON_CT_RADIX_GENERATED_H\n#include "ct_radix.h"\n\n'
    for n,q in pairs:
        text+=emit(plan(n,q),args.symbol or f'ct_radix_n{n}_q{q}')+'\n'
    text+='#endif\n'
    if args.check:
        if not args.out.exists() or args.out.read_text() != text:
            raise SystemExit(f'{args.out}: does not match public n,q generator')
        print(f'{args.out}: exact generator match')
    else: args.out.write_text(text)

if __name__ == '__main__': main()
