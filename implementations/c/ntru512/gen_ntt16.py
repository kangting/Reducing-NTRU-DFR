#!/usr/bin/env python3
"""Generate checked public Montgomery constants for the two-prime AVX2 NTT."""
import argparse
from pathlib import Path


def prime(n):
    return n >= 2 and all(n % d for d in range(2, int(n**0.5) + 1))


def main():
    moduli = ((12289, 11), (15361, 7))
    assert all(prime(p) and (p - 1) % 1024 == 0 and 2*p < 32768 for p, _ in moduli)
    assert moduli[0][0] * moduli[1][0] > 2*512*210**2
    lines = ['/* Generated by gen_ntt16.py. Public constants, not secret state. */',
             '#include <stdint.h>']
    for index, (p, g) in enumerate(moduli):
        r = 65536 % p
        for inverse in (False, True):
            values = [0] * 1024
            for k in range(1, 11):
                half = 1 << (k - 1)
                omega = pow(g, (p - 1) // (2*half), p)
                assert pow(omega, 2*half, p) == 1 and pow(omega, half, p) == p - 1
                if inverse:
                    omega = pow(omega, -1, p)
                w = 1
                for j in range(half):
                    values[half+j] = w*r % p
                    w = w*omega % p
            name = f'ntt16_{index}_' + ('inverse' if inverse else 'forward')
            lines.append(f'_Alignas(32) static const uint16_t {name}[1024] = {{')
            lines.extend('    ' + ','.join(map(str, values[j:j+16])) + ','
                         for j in range(0, 1024, 16))
            lines.append('};')
            rows = []
            for k in range(4):
                half = 1 << k
                rows.append([values[half+(lane & (half-1))]
                             if not inverse or lane & half else r for lane in range(16)])
            lines.append(f'_Alignas(32) static const uint16_t {name}_small[4][16] = {{')
            lines.extend('    {' + ','.join(map(str, row)) + '},' for row in rows)
            lines.append('};')
        values = [pow(1 << k, -1, p)*r % p for k in range(11)]
        lines.append(f'static const uint16_t ntt16_{index}_inverse_lengths[11] = '
                     + '{' + ','.join(map(str, values)) + '};')
    lines.append('_Alignas(32) static const uint16_t ntt16_upper_masks[4][16] = {')
    for k in range(4):
        lines.append('    {' + ','.join(str(65535 if lane & (1 << k) else 0)
                                       for lane in range(16)) + '},')
    lines.append('};')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).parent / 'ntt16_tables.h'
    text = '\n'.join(lines) + '\n'
    if args.check:
        if not path.is_file() or path.read_text() != text:
            raise ValueError('Generated NTT table differs: '+str(path))
    else:
        path.write_text(text)
    print('PASS: checked public two-prime NTT constants')


if __name__ == '__main__':
    main()
